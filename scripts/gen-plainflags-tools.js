#!/usr/bin/env node
// scripts/gen-plainflags-tools.js — write plainflags-tools.json from the REAL
// plain-flags relay: its `initialize` answer (less the negotiated version) and
// its `tools/list` answer. plainflags-stub.py serves the handshake from that
// file until the relay is started; test/plainflags-stub-drift.test.js fails
// when the file no longer matches the relay.
//
//   node scripts/gen-plainflags-tools.js            write <repo>/plainflags-tools.json
//   node scripts/gen-plainflags-tools.js --check    compare only; exit 1 when stale
//
// Isolation is scripts/test-harness.js's own (its helpers): a fresh temp HOME,
// the same self-check (so, like the harness, it refuses to run from a checkout
// whose parent holds wrap-browser-devtools-mcp.js — run it from a copy), and a
// before/after snapshot of the real cache root. The relay is started with the
// test launch hook and a temp sign-in list; no Brave starts.

const fs = require("node:fs");
const path = require("node:path");
const { spawnSync } = require("node:child_process");

const NOTE = "Generated by scripts/gen-plainflags-tools.js from the real plain-flags relay — do not edit. " +
  "plainflags-stub.py answers initialize and tools/list from it; test/plainflags-stub-drift.test.js keeps it current.";

if (process.argv.includes("--capture")) {
  // Child mode: runs under the harness env built below.
  const { isolated } = require("../test/helpers/isolation.js");
  if (!isolated()) { process.stderr.write("[gen-plainflags-tools] --capture outside the isolated env — refusing\n"); process.exit(2); }
  require("../test/helpers/plainflags-live.js").captureLive().then(
    (live) => { process.stdout.write(JSON.stringify(live)); },
    (e) => { process.stderr.write(`[gen-plainflags-tools] ${e.stack || e.message}\n`); process.exit(1); },
  );
} else {
  const { makeTempHome, harnessEnv, selfCheck, snapshot, diffSnapshots } = require("./test-harness.js");
  const REPO = path.resolve(__dirname, "..");
  const OUT = path.join(REPO, "plainflags-tools.json");
  const check = process.argv.includes("--check");
  const home = makeTempHome();
  let code = 0;
  try {
    const env = harnessEnv(home);
    const sc = selfCheck(env);
    if (!sc.ok) throw new Error(`REFUSING TO RUN — isolation self-check failed:\n  - ${sc.problems.join("\n  - ")}`);
    const before = snapshot();
    const r = spawnSync(process.execPath, [__filename, "--capture"], { cwd: REPO, env, encoding: "utf8", timeout: 120000, maxBuffer: 64 * 1024 * 1024 });
    if (r.status !== 0) throw new Error(`capture failed (status ${r.status}):\n${(r.stderr || "").slice(-3000)}`);
    const live = JSON.parse(r.stdout);
    const diff = diffSnapshots(before, snapshot());
    // Live sessions change their own lock files too; report, do not fail on, a diff.
    if (diff.length) process.stderr.write(`[gen-plainflags-tools] note: the real cache root changed during the run (${diff.length} entries — other sessions' relays?):\n  ${diff.join("\n  ")}\n`);
    const text = JSON.stringify({ _note: NOTE, ...live }, null, 2) + "\n";
    if (check) {
      let cur = null;
      try { cur = fs.readFileSync(OUT, "utf8"); } catch { /* missing */ }
      if (cur !== text) { process.stderr.write(`[gen-plainflags-tools] ${OUT} is STALE — run without --check\n`); code = 1; }
      else process.stderr.write(`[gen-plainflags-tools] ${OUT} is current (${live.toolsList.tools.length} tools)\n`);
    } else {
      fs.writeFileSync(OUT, text);
      process.stderr.write(`[gen-plainflags-tools] wrote ${OUT} (${live.toolsList.tools.length} tools, ${text.length} bytes)\n`);
    }
  } catch (e) {
    process.stderr.write(`[gen-plainflags-tools] ${e.message}\n`);
    code = 2;
  } finally {
    try { fs.rmSync(home, { recursive: true, force: true }); } catch { /* best-effort */ }
  }
  process.exitCode = code;
}
